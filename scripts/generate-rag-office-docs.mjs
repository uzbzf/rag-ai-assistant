function markdownToDocx(mdText) {
  const lines = mdText.split(/\r?\n/);
  const children = [];

  for (const rawLine of lines) {
    const line = rawLine.trim();
    if (!line || line === '---') continue;

    if (line.startsWith('# ')) {
      children.push(
        new Paragraph({
          text: line.slice(2).trim(),
          heading: HeadingLevel.HEADING_1,
          spacing: { before: 240, after: 120 },
        })
      );
    } else if (line.startsWith('## ')) {
      children.push(
        new Paragraph({
          text: line.slice(3).trim(),
          heading: HeadingLevel.HEADING_2,
          spacing: { before: 200, after: 100 },
        })
      );
    } else if (line.startsWith('### ')) {
      children.push(
        new Paragraph({
          text: line.slice(4).trim(),
          heading: HeadingLevel.HEADING_3,
          spacing: { before: 160, after: 80 },
        })
      );
    } else if (line.startsWith('|') && /^\|[\s\-|]+\|$/.test(line)) {
      // Skip markdown table separator line
      continue;
    } else {
      const clean = line.replace(/\*\*/g, '');
      children.push(
        new Paragraph({
          children: [new TextRun(clean)],
          spacing: { after: 80 },
        })
      );
    }
  }

  return new Document({
    sections: [{ children }],
  });
}

async function buildDocxFiles() {
  for (const name of ['price_list', 'faq']) {
    const mdPath = path.join(ragDocsDir, `${name}.md`);
    const mdContent = fs.readFileSync(mdPath, 'utf-8');
    const doc = markdownToDocx(mdContent);
    const buffer = await Packer.toBuffer(doc);

    const outPath = path.join(ragDocsDir, `${name}.docx`);
    const pubPath = path.join(publicRagDir, `${name}.docx`);
    fs.writeFileSync(outPath, buffer);
    fs.writeFileSync(pubPath, buffer);
    console.log(`Generated ${outPath}`);
  }
}

